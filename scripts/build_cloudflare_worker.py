#!/usr/bin/env python3
"""Bundle the static brief into a single Cloudflare Worker.

Usage:
    python scripts/build_cloudflare_worker.py
    cd cloudflare && npx wrangler deploy --temporary --compatibility-date 2026-10-23 worker.js
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HTML_PATH = ROOT / "site" / "index.html"
OUT_PATH = ROOT / "cloudflare" / "worker.js"


def main() -> None:
    html = HTML_PATH.read_text(encoding="utf-8")
    worker = f"""// Generated by scripts/build_cloudflare_worker.py — do not edit by hand.
const HTML = {json.dumps(html, ensure_ascii=True)};

export default {{
  async fetch(request) {{
    const url = new URL(request.url);
    if (url.pathname === "/health") {{
      return new Response(JSON.stringify({{ status: "ok", page: "video-mcp-brief" }}), {{
        headers: {{ "content-type": "application/json; charset=utf-8" }},
      }});
    }}
    if (url.pathname !== "/" && url.pathname !== "/index.html") {{
      return new Response("Not found", {{ status: 404, headers: {{ "content-type": "text/plain; charset=utf-8" }} }});
    }}
    return new Response(HTML, {{
      headers: {{
        "content-type": "text/html; charset=utf-8",
        "cache-control": "public, max-age=300",
        "x-content-type-options": "nosniff",
        "referrer-policy": "no-referrer",
        "content-security-policy": "default-src 'none'; style-src 'unsafe-inline'; img-src data:; base-uri 'none'; form-action 'none'",
      }},
    }});
  }},
}};
"""
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(worker, encoding="utf-8")
    print(f"Wrote {OUT_PATH} ({len(worker):,} bytes)")


if __name__ == "__main__":
    main()
